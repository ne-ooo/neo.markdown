import { readFile, writeFile } from 'node:fs/promises'

// The reviewed fixture is the semicolon-terminated subset of WHATWG entities.json.
const entities = JSON.parse(await readFile(new URL('../test/fixtures/entities.json', import.meta.url), 'utf8'))
const groups = new Map()
for (const [name, value] of Object.entries(entities)) {
  const points = Array.from(value, char => char.codePointAt(0))
  const key = points.join('.')
  if (!groups.has(key)) groups.set(key, { points, names: [] })
  groups.get(key).names.push(name.slice(0, -1))
}
const ordered = [...groups.values()].sort((a, b) => a.points[0] - b.points[0]
  || (a.points[1] ?? -1) - (b.points[1] ?? -1))
let previous = 0
const packed = ordered.map(({ points, names }) => {
  const delta = points[0] - previous
  previous = points[0]
  return [delta, ...points.slice(1)].map(point => point.toString(36)).join('.') + '=' + names.sort().join(',')
}).join('|')

const output = `// Generated by scripts/generate-entities.mjs from WHATWG entity data.
// Copyright WHATWG (Apple, Google, Mozilla, Microsoft). BSD-3-Clause.
// See THIRD_PARTY_NOTICES.md. Semicolon-terminated names only.
const packed = ${JSON.stringify(packed)}
let names: Map<string, string> | undefined

/** Decode the table on first use. Entries share values and store code-point deltas. */
export function namedEntity(name: string): string | undefined {
  if (!names) {
    names = new Map()
    let point = 0
    for (const group of packed.split('|')) {
      const [encoded, aliases] = group.split('=')
      const points = encoded.split('.').map(value => parseInt(value, 36))
      point += points[0]
      const value = String.fromCodePoint(point, ...points.slice(1))
      for (const alias of aliases.split(',')) names.set(alias + ';', value)
    }
  }
  return names.get(name)
}
`
await writeFile(new URL('../src/utils/entities-data.ts', import.meta.url), output)
console.log(`Packed ${Object.keys(entities).length} entity names into ${packed.length} ASCII characters`)
